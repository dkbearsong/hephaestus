"""
Output File Writer MCP Tool for Hephaestus
Writes text files to the project's root 'outputs' directory, specifically supporting
naming files after date and time values obtained from MCP datetime tools.
"""

import os
import re
import logging
from pathlib import Path
from typing import Dict, Any, Optional, List
from fastmcp import FastMCP

logger = logging.getLogger("hephaestus.mcp.file_writer")

# Project root directory and outputs target folder
ROOT_DIR = Path(__file__).resolve().parent.parent
OUTPUTS_DIR = ROOT_DIR / "outputs"

mcp = FastMCP("Outputs File Writer Tool")


def sanitize_filename(name: str) -> str:
    """
    Sanitizes a date/time string or filename to be filesystem-safe across all OSes.
    Replaces colons and unsafe characters with hyphens or underscores.
    """
    cleaned = name.strip()
    # Strip any directory traversal components
    cleaned = Path(cleaned).name
    # Replace colons (common in time HH:MM:SS) with hyphens
    cleaned = cleaned.replace(":", "-")
    # Replace ISO 'T' separator with underscore if followed by digit
    cleaned = re.sub(r"(\d{4}-\d{2}-\d{2})T(\d{2})", r"\1_\2", cleaned)
    # Replace any other illegal characters: < > " / \ | ? *
    cleaned = re.sub(r'[<>"/\\|?*]', '_', cleaned)
    # Ensure whitespace is preserved or underscored
    cleaned = cleaned.strip()
    return cleaned


@mcp.tool()
def write_datetime_output_file(
    date_time_str: str,
    content: Optional[str] = None
) -> Dict[str, Any]:
    """
    Writes a .txt file named after the provided date/time string into the project's 'outputs' directory.

    Args:
        date_time_str: Date and time string (e.g. '2026-09-04 14:17:05' or ISO string) obtained from the datetime MCP tool.
        content: Optional text content to write into the file. If omitted, a timestamp verification record is generated.

    Returns:
        Dictionary with success status, filename, resolved path, and bytes written.
    """
    OUTPUTS_DIR.mkdir(parents=True, exist_ok=True)

    safe_stem = sanitize_filename(date_time_str)
    if not safe_stem.endswith(".txt"):
        filename = f"{safe_stem}.txt"
    else:
        filename = safe_stem

    target_path = OUTPUTS_DIR / filename
    body = content if content is not None else (
        f"Timestamp: {date_time_str}\n"
        f"Source: MCP Date and Time Tool\n"
        f"Generated by: PreparationAgent via local LM Studio\n"
    )

    target_path.write_text(body, encoding="utf-8")
    logger.info(f"Wrote {len(body)} bytes to {target_path}")

    return {
        "success": True,
        "filename": filename,
        "path": str(target_path.resolve()),
        "bytes_written": len(body),
        "content_preview": body[:100]
    }


@mcp.tool()
def write_output_file(
    filename: str,
    content: str = ""
) -> Dict[str, Any]:
    """
    Writes a text file to the project's root 'outputs' directory.

    Args:
        filename: Name for the file (e.g. '2026-09-04_14-17-05.txt'). Colons are automatically converted to hyphens.
        content: The text content to write.

    Returns:
        Dictionary with success status, filename, and file path.
    """
    OUTPUTS_DIR.mkdir(parents=True, exist_ok=True)

    safe_name = sanitize_filename(filename)
    if not safe_name.endswith(".txt"):
        safe_name = f"{safe_name}.txt"

    target_path = OUTPUTS_DIR / safe_name
    target_path.write_text(content, encoding="utf-8")
    logger.info(f"Wrote {len(content)} bytes to {target_path}")

    return {
        "success": True,
        "filename": safe_name,
        "path": str(target_path.resolve()),
        "bytes_written": len(content)
    }


@mcp.tool()
def list_output_files() -> List[str]:
    """
    Lists all file names currently stored in the root 'outputs' directory.
    """
    if not OUTPUTS_DIR.exists():
        return []
    return [p.name for p in sorted(OUTPUTS_DIR.glob("*.txt")) if p.is_file()]


if __name__ == "__main__":
    mcp.run(transport="stdio")
