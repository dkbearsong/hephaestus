from pathlib import Path
from typing import Optional, List, Dict, Literal, Any, Union
from pydantic import BaseModel, Field

TargetPlatformLiteral = Literal[
    "GOOGLE_JULES",
    "CODEX_CLOUD",
    "LOCAL_CONTAINER",
    "GROK_BUILD",
    "DEVIN_AI",
    "CURSOR_DEVCONTAINER"
]


class WorkspaceTriggerPayload(BaseModel):
    """
    Input runtime payload received for each Jira trigger.
    """
    ticket_key: str = Field(..., description="Jira issue key, e.g. PROJ-123")
    mode: Literal["PROMPT_NEW", "PROMPT"] = Field(
        ...,
        description="PROMPT_NEW for brand new repository creation, PROMPT for existing repository modifications"
    )
    target_platform: TargetPlatformLiteral = Field(
        ...,
        description="Downstream coding agent platform"
    )
    repo_url: Optional[str] = Field(
        None,
        description="Target GitHub repo URL. None if creating a new project from scratch"
    )
    staging_dir: Path = Field(
        ...,
        description="Path where parser saved prompt.md, preparations.md, and /staged_files/"
    )
    workspaces_root: Path = Field(
        ...,
        description="Base directory where active project directories live"
    )
    github_token: Optional[str] = Field(
        None,
        description="Optional GitHub App token or PAT for authenticated repository cloning"
    )
    custom_branch_name: Optional[str] = Field(
        None,
        description="Optional custom branch name override"
    )
    skip_clone: bool = Field(
        False,
        description="If True, skips running git clone locally (e.g. for cloud agents or when clone: false flag is set)"
    )
    flags: Dict[str, Any] = Field(
        default_factory=dict,
        description="Deterministic YAML configuration flags extracted from <|flags|>"
    )


class PrepSummary(BaseModel):
    """
    Structured summary output returned by the Preparation Agent.
    """
    status: Literal["READY", "BLOCKED"]
    working_directory: str
    branch_name: str
    detected_commands: Dict[str, Optional[str]] = Field(
        default_factory=lambda: {"build": None, "test": None, "lint": None}
    )
    files_modified: List[str] = Field(default_factory=list)
    blocker_reason: Optional[str] = None


class ProviderConfig(BaseModel):
    """
    Configuration and manifest details generated by the provider preparation engine.
    """
    platform: TargetPlatformLiteral
    rules_applied: List[str] = Field(default_factory=list)
    manifest_files: List[str] = Field(default_factory=list)
    environment_variables: Dict[str, str] = Field(default_factory=dict)
    mount_points: Dict[str, str] = Field(default_factory=dict)
    entry_points_verified: List[str] = Field(default_factory=list)
    hooks_configured: Dict[str, str] = Field(default_factory=dict)


class RepoCoordinates(BaseModel):
    """Repository Git metadata and coordinates."""
    repo_url: Optional[str] = None
    branch: str
    commit_sha: Optional[str] = None


class PromptLocation(BaseModel):
    """Filepaths where prompt and preparations were staged."""
    prompt_file: str
    preparations_file: Optional[str] = None


class HarnessManifest(BaseModel):
    """Standardized harness_manifest.json metadata contract."""
    ticket_key: str
    mode: Literal["PROMPT_NEW", "PROMPT"]
    target_platform: TargetPlatformLiteral
    repo_coordinates: RepoCoordinates
    prompt_location: PromptLocation
    detected_commands: Dict[str, Optional[str]] = Field(
        default_factory=lambda: {"build": None, "test": None, "lint": None}
    )
    created_at: str


class HandoffState(BaseModel):
    """
    State tracking record persisted in the workspace and passed to downstream agent execution.
    """
    ticket_key: str
    mode: Literal["PROMPT_NEW", "PROMPT"]
    target_platform: TargetPlatformLiteral
    working_directory: str
    branch_name: str
    ready_for_execution: bool
    cloned: bool = True
    flags: Dict[str, Any] = Field(default_factory=dict)
    prep_summary: PrepSummary
    provider_config: ProviderConfig
    created_at: str
    handoff_file_path: Optional[str] = None
    manifest_path: Optional[str] = None
